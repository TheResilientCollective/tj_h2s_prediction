"""Regenerate every figure and table in the report, in order.

    uv venv .venv && uv pip install -r requirements.txt
    .venv/bin/python run_all.py

Each step is an ordinary standalone script and can be run on its own; this only
runs them in sequence and reports what was produced. Raw inputs are cached under
``data/`` — delete that directory to force a fresh pull from the public sources
listed in ``common.SOURCES``.

``--manifest`` additionally rewrites ``APPENDIX.md``, the provenance table that
maps every figure and table in the report back to the script that produced it
and the URLs that script read.
"""

from __future__ import annotations

import argparse
import importlib
import sys
import time
from pathlib import Path

import common as C

#: (module, what it produces) in report order.
STEPS = [
    ("fig01_complaint_record", "Figure 1 — the complaint record"),
    ("fig02_dose_response", "Figure 2 — odour dose-response"),
    ("fig03_complaint_conditions", "Figure 3 — conditions at complaint time"),
    ("fig04_exceedance_midnight", "Figure 4 — exceedance record, midnight-centred"),
    ("fig05_exceedance_clock", "Figure 5 — exceedance clock, midnight-centred"),
    ("fig06_seasonality_temperature", "Figure 6 — seasonality and temperature"),
    ("tbl07_model_features", "Table 7 — model feature inventory"),
    ("fig07_model_performance", "Figure 7 — model performance"),
]


def write_manifest() -> None:
    """Regenerate APPENDIX.md from the scripts' own docstrings and SOURCES."""
    lines = [
        "# Appendix — how every figure was made",
        "",
        "Generated by `run_all.py --manifest`; do not edit by hand.",
        "",
        "Every script below is standalone: `python <script>.py` reproduces its",
        "figure and tables from the public URLs in the data-source table, with no",
        "credentials. Intermediate pulls are cached in `data/` (gitignored).",
        "",
        "## Scripts",
        "",
        "| Output | Script | What it does |",
        "|---|---|---|",
    ]
    for mod, label in STEPS:
        doc = (importlib.import_module(mod).__doc__ or "").strip().splitlines()
        summary = doc[0] if doc else ""
        summary = summary.split("—", 1)[-1].strip() if "—" in summary else summary
        lines.append(f"| {label} | [`{mod}.py`]({mod}.py) | {summary} |")

    lines += [
        "",
        "## Data sources",
        "",
        "All public; no authentication.",
        "",
        "| Cached as | URL | What it is |",
        "|---|---|---|",
    ]
    for name, (url, desc) in C.SOURCES.items():
        lines.append(f"| `{name}` | {url} | {desc} |")

    lines += [
        "",
        "## Generated figures",
        "",
        *(f"- `figures/{p.name}`" for p in sorted(C.FIGURES.glob("*.png"))),
        "",
        "## Generated tables",
        "",
        *(f"- `tables/{p.name}`" for p in sorted(C.TABLES.glob("*"))),
        "",
    ]
    out = C.HERE / "APPENDIX.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out.name}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", action="store_true",
                    help="also regenerate APPENDIX.md")
    ap.add_argument("--only", nargs="*", help="run only these module names")
    args = ap.parse_args()

    steps = [s for s in STEPS if not args.only or s[0] in args.only]
    failed = []
    for mod, label in steps:
        print(f"\n=== {label}  ({mod}.py)")
        t0 = time.time()
        try:
            importlib.import_module(mod).main()
        except Exception as exc:  # noqa: BLE001 — report and keep going
            print(f"  FAILED: {type(exc).__name__}: {exc}")
            failed.append(mod)
        else:
            print(f"  ok ({time.time() - t0:.1f}s)")

    if args.manifest:
        print()
        write_manifest()

    if failed:
        print(f"\n{len(failed)} step(s) failed: {', '.join(failed)}")
        return 1
    print(f"\nall {len(steps)} steps ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
